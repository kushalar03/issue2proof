const {chromium}=require('playwright');
const fs=require('fs');
(async()=>{
 const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 await page.goto('http://127.0.0.1:8000');
 await page.getByRole('button',{name:'Live AI pricing repair',exact:true}).click();
 await page.locator('#results').getByText('verified',{exact:true}).waitFor();
 await page.screenshot({path:'submission/pricing-live.png',fullPage:true});
 await page.getByRole('button',{name:'Live uploaded-project repair',exact:true}).click();
 await page.locator('#results').getByText('checks passed',{exact:true}).waitFor();
 await page.locator('#results details').first().click();
 await page.screenshot({path:'submission/repository-live.png',fullPage:true});
 const download=await page.request.get('http://127.0.0.1:8000/api/examples/live-repository-repair/artifacts');
 if(download.status()!==200)throw Error('Artifact download failed');
 await page.getByRole('button',{name:'Live bad-candidate rejection',exact:true}).click();
 await page.locator('#results').getByText('unresolved',{exact:true}).waitFor();
 await page.screenshot({path:'submission/rejection-live.png',fullPage:true});
 await page.getByText('Investigate your Python project',{exact:true}).click();
 await page.locator('#repository').setInputFiles('examples/pricing-project.zip');
 await page.locator('#bug-report').fill('Clamp excess discounts to zero while preserving ordinary totals.');
 await page.locator('#inspect-project').click();
 await page.locator('#results').getByText('awaiting model',{exact:true}).waitFor();
 if(await page.locator('.holdout').count()!==2)throw Error('Independent test selection missing');
 if(errors.length)throw Error(errors.join('\n'));
 fs.writeFileSync('artifacts/browser-validation.json',JSON.stringify({passed:true,checks:['saved live pricing evidence','saved live repository evidence','saved live rejection evidence','artifact ZIP download','repository upload','independent test selection'],page_errors:errors},null,2));
 console.log('Browser smoke checks passed');await browser.close();
})().catch(error=>{console.error(error);process.exit(1)});
