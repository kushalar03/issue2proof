const {chromium}=require('playwright');
const fs=require('fs');
(async()=>{
 const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
 const context=await browser.newContext({viewport:{width:1440,height:1000},recordVideo:{dir:'submission/raw-video',size:{width:1440,height:1000}}});
 const page=await context.newPage();
 const pause=ms=>page.waitForTimeout(ms);
 await page.goto('http://127.0.0.1:8000');await pause(9000);
 await page.getByRole('button',{name:'Live AI pricing repair',exact:true}).click();
 await page.locator('#results').scrollIntoViewIfNeeded();await pause(5000);
 await page.locator('#results details').first().click();await pause(5000);
 await page.locator('#results details').nth(1).click();await page.mouse.wheel(0,380);await pause(8000);
 await page.getByRole('button',{name:'Live uploaded-project repair',exact:true}).click();
 await page.locator('#results').scrollIntoViewIfNeeded();await pause(9000);
 await page.locator('#results details').nth(2).click();await pause(7000);
 await page.mouse.wheel(0,440);await pause(7000);
 await page.locator('#results details').nth(5).click();await pause(10000);
 await page.getByRole('button',{name:'Live bad-candidate rejection',exact:true}).click();
 await page.locator('#results').scrollIntoViewIfNeeded();await pause(4000);
 await page.locator('#results details').nth(3).click();
 await page.locator('#results details').nth(4).click();await page.mouse.wheel(0,350);await pause(9000);
 await page.getByRole('button',{name:'Live uploaded-project repair',exact:true}).click();
 await page.locator('#results').scrollIntoViewIfNeeded();await pause(10000);
 const video=page.video();await context.close();fs.renameSync(await video.path(),'submission/demo-screen.webm');await browser.close();
 console.log('Demo recording saved');
})().catch(error=>{console.error(error);process.exit(1)});
